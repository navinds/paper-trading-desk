#!/usr/bin/env python3
"""Position sizing for trader-budget. Standard library only, no network.

Default mode: sizes ONE intraday trade from trader/plan.json (written by
trader-exit) to your budget and your max loss per trade, charges included,
then writes one entry order to trader/orders.json in the shape of Kite's
place_order (Zerodha's MCP server), with the stop-loss order that goes in
right after the entry fills. It never places anything: trader-risk checks
the order and trader-broker asks you yes or no.

    python3 size.py                                  # trader/plan.json + trader/config.json
    python3 size.py --write                          # write trader/orders.json
    python3 size.py --limit                          # a limit order at the plan's entry
    python3 size.py --limit 1227.50 --write          # a limit order at 1227.50
    python3 size.py --now "2026-10-19 09:50" --json  # pin the clock (IST)

How many shares. Whole shares only.

    shares = the smallest of
      max loss       the most shares whose loss at the stop PLUS the round-trip
                     charges (buy at the entry, sell at the stop) fits
                     max_loss_per_trade_inr ("include_charges": false sizes
                     on entry minus stop alone)
      position cap   budget x max_position_pct / entry
      max order      max_order_inr / entry
      cash           (budget minus the cash buffer) / entry
                     (and no more than the cash in trader/portfolio.json, if you have one)

The charges are Zerodha's equity intraday (MIS) schedule, zerodha.com/charges
(read 2026-10-25): brokerage 0.03% or Rs 20 an executed order, whichever is
lower; STT 0.025% on the sell side; NSE transaction charges 0.00307%; SEBI
Rs 10 a crore; stamp duty 0.003% on the buy side; GST 18% on brokerage +
transaction + SEBI charges. Delivery (CNC): no brokerage, STT 0.1% both sides,
stamp 0.015%. Another broker: put its numbers in "charges" in the config.

The entry it sizes at: a limit order's limit price; for a market order the
plan's entry, or the price in trader/prices.json if that is fresh (under 15
minutes old) and higher, because a price that ran up since the plan means a
bigger loss at the same stop. Zero shares (the stop is too far away for your
max loss) is a plain refusal: no order is written. So is a reward:risk under
min_reward_risk (the price ran toward the target since the plan).

Kite has no bracket order for intraday (MIS), and Zerodha's GTT one-cancels-
other does not take MIS. So the order file holds the entry, and next to it
"stop_loss_order": the SL-M sell at your stop that trader-broker places the
moment the entry fills. The target is watched by trader-alerts and taken
with a sell ticket (trader-broker flatten).

Weights mode (kept from v1): split a budget across a list of stocks by
weight, for delivery (CNC), whole shares at the prices in trader/prices.json.

    python3 size.py --weights RELIANCE=30,TCS=25,HDFCBANK=25,INFY=20 --prices trader/prices.json
    python3 size.py --targets my-weights.json --budget 200000 --write

  1. cash buffer   budget x cash_buffer_pct stays in cash, never invested
  2. weights       renormalised to 100 over the stocks you keep (blocked
                   tickers are dropped first; --top N keeps the N biggest)
  3. cap           no stock gets more than max_position_pct of the budget;
                   anything over the cap is shared out to the others by
                   weight, again and again until nobody is over
  4. min order     a slice under min_order_inr is dropped and its weight
                   shared out
  5. whole shares  floor each slice, then one more share at a time for the
                   stock furthest below its slice while cash lasts

Money that cannot be invested is reported as "left idle", never hidden.
"""

